def clear_runs(paragraph):
    p = paragraph._p
    for child in list(p):
        if child.tag == qn("w:r"):
            p.remove(child)

def set_text(paragraph, text, *, bold=None, size_pt=16, font="TH Sarabun New", align=None):
    clear_runs(paragraph)
    run = paragraph.add_run(text)
    run.bold = bold
    run.font.name = font
    run.font.size = Pt(size_pt)
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:eastAsia"), font)
    if align is not None:
        paragraph.alignment = align
    # keep Thai justify for body where template used it
    pf = paragraph.paragraph_format
    if pf.line_spacing is None:
        pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE

def set_label_value(paragraph, label, value):
    clear_runs(paragraph)
    r1 = paragraph.add_run(label)
    r1.font.name = "TH Sarabun New"
    r1.font.size = Pt(16)
    r1._element.get_or_add_rPr().get_or_add_rFonts().set(qn("w:eastAsia"), "TH Sarabun New")
    r2 = paragraph.add_run(value)
    r2.font.name = "TH Sarabun New"
    r2.font.size = Pt(16)
    r2._element.get_or_add_rPr().get_or_add_rFonts().set(qn("w:eastAsia"), "TH Sarabun New")

