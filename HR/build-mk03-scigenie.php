function esc(string $s): string
{
    return htmlspecialchars($s, ENT_XML1 | ENT_COMPAT, 'UTF-8');
}

function runsFromText(string $text, bool $bold = false): string
{
    $rPr = $bold
        ? '<w:rPr><w:rFonts w:ascii="TH Sarabun New" w:hAnsi="TH Sarabun New" w:cs="TH Sarabun New"/><w:b/><w:sz w:val="32"/><w:szCs w:val="32"/></w:rPr>'
        : '<w:rPr><w:rFonts w:ascii="TH Sarabun New" w:hAnsi="TH Sarabun New" w:cs="TH Sarabun New"/><w:sz w:val="32"/><w:szCs w:val="32"/></w:rPr>';
    $parts = preg_split("/\n/", $text) ?: [''];
    $xml = '';
    foreach ($parts as $i => $line) {
        if ($i > 0) {
            $xml .= '<w:r>' . $rPr . '<w:br/></w:r>';
        }
        $xml .= '<w:r>' . $rPr . '<w:t xml:space="preserve">' . esc($line) . '</w:t></w:r>';
    }
    return $xml;
}

function p(string $text, string $align = 'both', bool $bold = false, int $spaceAfter = 120): string
{
    $jc = $align === 'center' ? 'center' : ($align === 'left' ? 'left' : 'both');
    return '<w:p>'
        . '<w:pPr><w:jc w:val="' . $jc . '"/><w:spacing w:after="' . $spaceAfter . '" w:line="360" w:lineRule="auto"/>'
        . '<w:ind w:firstLine="0"/></w:pPr>'
        . runsFromText($text, $bold)
        . '</w:p>';
}

function imageParagraph(string $relId, int $cx, int $cy): string
{
    return '<w:p>'
        . '<w:pPr><w:jc w:val="center"/><w:spacing w:after="80"/></w:pPr>'
        . '<w:r>'
        . '<w:drawing>'
        . '<wp:inline distT="0" distB="0" distL="0" distR="0">'
        . '<wp:extent cx="' . $cx . '" cy="' . $cy . '"/>'
        . '<wp:docPr id="1" name="SCiGENIE Flow"/>'
        . '<a:graphic xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">'
        . '<a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture">'
        . '<pic:pic xmlns:pic="http://schemas.openxmlformats.org/drawingml/2006/picture">'
        . '<pic:nvPicPr><pic:cNvPr id="0" name="scigenie-ai-flow.png"/><pic:cNvPicPr/></pic:nvPicPr>'
        . '<pic:blipFill><a:blip r:embed="' . $relId . '"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>'
        . '<pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="' . $cx . '" cy="' . $cy . '"/></a:xfrm>'
        . '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr>'
        . '</pic:pic></a:graphicData></a:graphic>'
        . '</wp:inline></w:drawing></w:r></w:p>';
}

$body = '';
$hasImage = false;
foreach ($sections as $sec) {
    $level = $sec['level'] ?? 'body';
    if ($level === 'spacer') {
        $body .= p(' ', 'left', false, 60);
        continue;
    }
    if ($level === 'center_bold') {
        $body .= p((string) $sec['title'], 'center', true, 80);
        continue;
    }
    if ($level === 'center') {
        $body .= p('', 'left', false, 200);
        $body .= p((string) $sec['title'], 'center', true, 160);
        if (!empty($sec['body'])) {
            $body .= p((string) $sec['body'], 'center', false, 200);
        }
        continue;
    }
    if ($level === 'image') {
        // 6.2 inch wide, keep aspect 1600x2200
        $cx = 5670000;
        $cy = (int) round($cx * (2200 / 1600));
        $body .= imageParagraph('rIdImage1', $cx, $cy);
        if (!empty($sec['caption'])) {
            $body .= p((string) $sec['caption'], 'center', false, 200);
        }
        $hasImage = true;
        continue;
    }
    if ($level === 'h') {
        $body .= p('', 'left', false, 80);
        $body .= p((string) $sec['title'], 'left', true, 80);
        if (!empty($sec['note'])) {
            $body .= p((string) $sec['note'], 'left', false, 80);
        }
        if (!empty($sec['body'])) {
            $body .= p((string) $sec['body'], 'both', false, 160);
        }
        continue;
    }
    if (!empty($sec['body'])) {
        $body .= p((string) $sec['body'], 'both', false, 160);
    }
}

